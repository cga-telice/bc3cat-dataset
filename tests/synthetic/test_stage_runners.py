_OC = "OBRA CIVIL"
_HAS_DATA = (
    config.chapter_path(_OC).exists()
    and all(config.stage_path(_OC, n).exists() for n in (3, 4, 5, 7))
)
_skip_no_data = pytest.mark.skipif(not _HAS_DATA, reason="OBRA CIVIL intermediate JSONs absent")


def _load(path):
    import json
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def _norm(obj):
    """JSON round-trip — normalises tuple->list etc., exactly as the notebooks'
    `json.dump` does on write. s04's `evaluate_formula` can return a tuple (when
    a resolved formula is a comma-separated expression); on disk that serialises
    to a JSON array, so the golden file (re-loaded) holds a list. Comparing
    JSON-normalised values is the faithful "modulo json" equivalence the sprint
    acceptance specifies. Applied per-item to keep memory bounded on the large
    chapter files."""
    import json
    return json.loads(json.dumps(obj, ensure_ascii=False))


def _assert_golden(got, gold_path):
    gold = _load(gold_path)
    assert list(got.keys()) == list(gold.keys())
    for k in got:
        assert _norm(got[k]) == gold[k], f"item {k} diverges from golden"


@_skip_no_data
def test_golden_stage3():
    stage2 = _load(config.chapter_path(_OC))
    got = run_stage3(stage2)
    del stage2
    _assert_golden(got, config.stage_path(_OC, 3))


