"""Sprint 17 — Phase D Task D1: equivalence harness for the stage runners.

Two tiers:

* **Always-on unit tests** — tiny inline fixtures, no real IO. One per stage
  runner exercising the core transform, plus purity (input-not-mutated),
  determinism (run-twice-equal), the `run_stages_3_to_7` chain, an
  import-hygiene audit (no synthetic-mutation-stack imports), and a
  no-side-effects-at-import check.

* **Data-gated golden tests** — skipped when the committed
  `data/intermediate/OBRA CIVIL/*.json` are absent; otherwise assert each
  runner reproduces the committed golden stage file. These are the
  faithfulness gate for the extraction.

RECONCILIATION NOTE (Sprint 17): s04 carried an inline copy of
`translate_formula_to_python` that had drifted from the canonical
`utils.z_formula_processing` export (no `=`->`==` mapping, `\b`-anchored
substitution, no `quote_second_term` call). The committed golden stage4 was
generated by the *inline* variant — empirically, the canonical util mismatches
golden on ~4% of a sampled chapter (it turns `==` into `====`). So `run_stage4`
preserves the inline notebook semantics (relocated as
`_translate_formula_to_python_s04`); two tests below pin that decision.
"""

